HEADLINE_LIMIT = 220

_FULLWIDTH_DIGITS = str.maketrans("０１２３４５６７８９", "0123456789")


class OpenDartError(RuntimeError):
    """A window could not be read, or came back implausibly empty."""


def _headers() -> dict:
    return {"User-Agent": USER_AGENT, "Accept": "application/json"}


def api_key() -> str:
    """The credential, or a loud refusal.

    An unset GitHub secret maps to the EMPTY STRING rather than being absent,
    and OpenDART answers a keyless request with a 302 to an HTML page. Refusing
    here turns that into one readable sentence instead of a JSON parse error
    forty lines later.
    """
    key = (os.environ.get("OPENDART_API_KEY_KR") or "").strip()
    if not key:
        raise OpenDartError(
            "OPENDART_API_KEY_KR is empty or unset. OpenDART answers a keyless "
            "request with a 302 to an HTML error page, so this fails here "
            "rather than as an unexplained parse error later.")
    if not re.fullmatch(r"[0-9a-zA-Z]{40}", key):
        raise OpenDartError(
            f"OPENDART_API_KEY_KR is {len(key)} characters; the published spec "
            f"says the key is 40 alphanumeric characters. Refusing to spend a "
            f"run on a malformed credential.")
    return key


def days_from_env(default_days: int | None = None) -> int:
    """How many days back to read. Set by the workflow, so a backfill is a
    longer window through the same path rather than a script of its own."""
    raw = (os.environ.get("TIT_DART_DAYS") or "").strip()
    if not raw:
        return default_days if default_days is not None else DEFAULT_DAYS
    if not re.fullmatch(r"\d{1,4}", raw):
        raise OpenDartError(
            f"TIT_DART_DAYS holds {raw!r}, which is not a number of days")
    days = int(raw)
    if days < 1:
        raise OpenDartError("TIT_DART_DAYS must be at least 1 day")
    # Without a corp_code the published spec limits a search to three months.
    if days > 90:
        raise OpenDartError(
            f"TIT_DART_DAYS is {days}. OpenDART limits a keyless-of-company "
            f"search to three months, so a longer window silently returns a "
            f"shorter one. Run consecutive 90-day windows instead.")
    return days


def window(days: int, *, today: datetime | None = None) -> tuple[str, str]:
    """The API's date window, in the YYYYMMDD form it insists on."""
    end = today or datetime.now(timezone.utc)
    start = end - timedelta(days=days)
    return start.strftime("%Y%m%d"), end.strftime("%Y%m%d")


def viewer_url(rcept_no: str) -> str | None:
    """The filing's own page on DART, keyed by its receipt number.

    This is the form OpenDART's own field documentation gives for `rcept_no`.
    See trap 2 for why it is not the English viewer.
    """
    clean = (rcept_no or "").strip()
    if not re.fullmatch(r"\d{14}", clean):
        return None
    return VIEWER_URL.format(rcept_no=clean)


def _squeeze(text: str) -> str:
    """Collapse whitespace and fold full-width digits to ASCII.

    The fold is load-bearing, not cosmetic: see trap 4. NFKC would do it and
    would also rewrite the ㆍ that the report-name allowlist matches on, so the
    translation table is deliberately narrow.
    """
    folded = (text or "").translate(_FULLWIDTH_DIGITS)
    return re.sub(r"\s+", " ", folded).strip()


def _date(value: str) -> str | None:
    """'20260728' or '2026-07-28' -> '2026-07-28'."""
    text = re.sub(r"\D", "", (value or "").strip())
    if len(text) != 8:
        return None
    try:
        return datetime.strptime(text, "%Y%m%d").date().isoformat()
    except ValueError:
        return None


def strip_amendment(report_nm: str) -> tuple[str, str | None]:
    """Split a report name into its title and its amendment marker, if any."""
    name = _squeeze(report_nm)
    for prefix in AMENDMENT_PREFIXES:
        if name.startswith(prefix):
            return name[len(prefix):].strip(), prefix
    return name, None


def english_label(report_nm: str) -> str | None:
    """FSS's own English name for this report type, or None if not allowlisted."""
    name, _ = strip_amendment(report_nm)
    return REPORT_NAMES.get(name)


def is_wanted(report_nm: str) -> bool:
    """Whether this row is one of the typed leadership items, unamended."""
    name, amendment = strip_amendment(report_nm)
    if amendment:
        return False
    return name in REPORT_NAMES


def _payload(url: str, params: dict, *, timeout: int, session) -> dict:
    get = (session or requests).get
    resp = get(url, params=params, headers=_headers(), timeout=timeout)
    status_code = getattr(resp, "status_code", 0)
    if status_code != 200:
        raise OpenDartError(
            f"{url} returned HTTP {status_code}. A request with no crtfc_key "
            f"answers 302 with an HTML error page, so check the key is set "
            f"before looking anywhere else.")
    try:
        payload = resp.json()
    except ValueError as exc:
        raise OpenDartError(
            f"{url} did not return JSON: {getattr(resp, 'text', '')[:160]!r}"
        ) from exc
    if not isinstance(payload, dict):
        raise OpenDartError(f"{url} returned a non-object response")

    # HTTP 200 does not mean success here: an unregistered key answers
    # 200 {"status":"010"}. Verified live, keyless, 2026-07-29.
    status = str(payload.get("status") or "")
    message = str(payload.get("message") or "")
    if status == "000":
        return payload
    if status == "013":            # 조회된 데이타가 없습니다 — an empty window
        return {"status": status, "list": [], "total_page": 1}
    if status in {"010", "011", "012", "101", "901"}:
        raise OpenDartError(
            f"OpenDART rejected the credential or the caller (status {status}: "
            f"{message}). Nothing is retried: a bad key does not become good.")
    if status == "020":
        raise OpenDartError(
            f"OpenDART request quota exceeded (status 020: {message}). The "
            f"documented allowance is 20,000 requests a day.")
    if status == "800":
        raise OpenDartError(f"OpenDART is under maintenance (status 800: {message})")
    raise OpenDartError(f"OpenDART returned status {status}: {message}")


def fetch_page(detail_type: str, start: str, end: str, page: int, *, key: str,
               timeout: int = 45, session=None) -> tuple[list[dict], int]:
    """One page of one detail type. Returns (rows, total_page)."""
    payload = _payload(LIST_URL, {
        "crtfc_key": key,
        "bgn_de": start,
        "end_de": end,
        "pblntf_detail_ty": detail_type,
        "page_no": page,
        "page_count": PAGE_SIZE,
        "sort": "date",
        "sort_mth": "desc",
    }, timeout=timeout, session=session)
    rows = payload.get("list")
    if rows is None:
        raise OpenDartError(
            f"{detail_type} returned status 000 with no 'list' key "
            f"(keys: {sorted(payload)[:8]}). The response shape has changed.")
    if not isinstance(rows, list):
        raise OpenDartError(f"{detail_type} returned a non-list 'list' key")
    try:
        total_page = max(1, int(payload.get("total_page") or 1))
    except (TypeError, ValueError):
        total_page = 1
    return rows, total_page


def fetch_company(corp_code: str, *, key: str, timeout: int = 45,
                  session=None) -> dict:
    """One filer's registration record. Read for `corp_name_eng` and nothing
    else — see the NAMES note in the module docstring."""
    return _payload(COMPANY_URL, {"crtfc_key": key, "corp_code": corp_code},
                    timeout=timeout, session=session)


def english_name(corp_code: str, *, key: str, cache: dict, session=None) -> str:
    """The filer's OWN registered English name, or '' if DART holds none.

    Cached per run: one event per company is the normal case, so this is a
    handful of extra requests a week rather than one per row.
    """
    code = re.sub(r"\D", "", str(corp_code or ""))
    if not re.fullmatch(r"\d{8}", code):
        return ""
    if code in cache:
        return cache[code]
    try:
        payload = fetch_company(code, key=key, session=session)
    except OpenDartError as exc:
        # A single filer's registration record failing must not lose the
        # window. The row is declined below because it has no English name,
        # and the count is printed.
        print(f"[{COLLECTOR}] company.json failed for {code}: {exc}")
        cache[code] = ""
        return ""
    name = _squeeze(payload.get("corp_name_eng") or "")
    cache[code] = name
    return name


def _row(entry: dict, english: str) -> dict | None:
    """One list.json row as a raw dict, or None if it is declined.

    `english` is the filer's registered English name, supplied by the caller so
    this stays a pure function that a test can drive without a network.
    """
    report_nm = _squeeze(entry.get("report_nm") or "")
    if not is_wanted(report_nm):
        return None
    label = english_label(report_nm)
    corp_name_kr = _squeeze(entry.get("corp_name") or "")
    company = _squeeze(english)
    url = viewer_url(entry.get("rcept_no") or "")
    published = _date(entry.get("rcept_dt") or "")
    rcept_no = re.sub(r"\D", "", str(entry.get("rcept_no") or ""))
    corp_cls = (entry.get("corp_cls") or "").strip().upper()

    # No English name, no record. Romanising a Korean company name here would
    # be this file inventing an identity, and a Hangul company_key produces a
    # slug that 404s on the live host. See the NAMES note.
    if not (company and corp_name_kr and url and published and rcept_no):
        return None

    market = MARKETS.get(corp_cls, "the Korea Exchange")
    body = (
        f"{company} ({corp_name_kr}) filed this disclosure with the Financial "
        f"Supervisory Service's DART system on {published}, under receipt "
        f"number {rcept_no}. The filer is on {market}. The quoted line above "
        f"is the report title the exchange's own filing system assigned, and "
        f"the Financial Supervisory Service publishes it in English as "
        f"\"{label}\". A Korean listed company must disclose a change of its "
        f"representative director, and must separately report the appointment, "
        f"dismissal or early retirement of an independent director, which is "
        f"what makes these comparable across employers rather than the ones an "
        f"outlet chose to write about. The title states that the change "
        f"happened; it does not state which direction it went, and nothing "
        f"here infers one."
    )

    return {
        # The report title is QUOTED, following collectors/bse_india.py: closing
        # the quote puts a non-space character after any figure, so the
        # magnitude-suffix regex in pipeline/validate.py cannot glue a digit at
        # the end of this line to a letter at the start of the next.
        "raw_text": f"\"{report_nm}\" ({label})\n\n{body}",
        "headline": f"{company}: {label}"[:HEADLINE_LIMIT],
        "source_url": url,
        "source_name": SOURCE_NAME,
        "discovery_url": url,
        "published_date": published,
        "company": company,
        "country": "South Korea",
        # Listed on a Korean exchange, which is what the source IS, except for
        # corp_cls E which is a filer with no listing.
        "employer_type": "public" if corp_cls in {"Y", "K", "N"} else "",
        "report_nm": report_nm,
        "report_label": label,
        "corp_name_kr": corp_name_kr,
        "corp_code": re.sub(r"\D", "", str(entry.get("corp_code") or "")),
        "rcept_no": rcept_no,
        "corp_cls": corp_cls,
        "collector": COLLECTOR,
        "fetched_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }


def collect(queries=None, *, days: int | None = None,
            detail_types: tuple = (), today: datetime | None = None,
            session=None, key: str | None = None) -> list[dict]:
    """Every allowlisted leadership filing in the window.

    `queries` is accepted and ignored so this collector is interchangeable with
    the others in run_collect: there is nothing to search for, the exchange's
    own report titles ARE the population.
    """
    wanted = tuple(detail_types) or DETAIL_TYPES
    crtfc = key or api_key()
    start, end = window(days if days is not None else days_from_env(),
                        today=today)
    out: list[dict] = []
    seen: set[str] = set()
    names: dict[str, str] = {}
    read = 0
    refused = 0
    no_english = 0

    for detail_type in wanted:
        kept = 0
        page = 1
        total_page = 1
        while page <= min(total_page, MAX_PAGES):
            if session is None:
                time.sleep(REQUEST_DELAY)
            rows, total_page = fetch_page(detail_type, start, end, page,
                                          key=crtfc, session=session)
            if not rows:
                break
            read += len(rows)
            for entry in rows:
                name, _ = strip_amendment(_squeeze(entry.get("report_nm") or ""))
                if name in REFUSED_REPORT_NAMES:
                    refused += 1
                    continue
                if not is_wanted(entry.get("report_nm") or ""):
                    continue
                english = english_name(entry.get("corp_code") or "",
                                       key=crtfc, cache=names, session=session)
                item = _row(entry, english)
                if item is None:
                    if not english:
                        no_english += 1
                    continue
                if item["source_url"] in seen:
                    continue
                seen.add(item["source_url"])
                out.append(item)
                kept += 1
            page += 1
        print(f"[{COLLECTOR}] {detail_type}: {kept} filings")

    print(f"[{COLLECTOR}] {start}..{end}: {read} rows read, {len(out)} usable, "
          f"{refused} refused by name, {no_english} declined for no English name")
    if len(out) < MIN_ROWS_PER_WINDOW:
        raise OpenDartError(
            f"{start}..{end} produced {len(out)} filings from {read} rows. "
            f"Korea files 12 to 49 of these a week (measured over twelve weeks "
            f"to 2026-07-29), so this is the report titles having moved, a "
            f"detail code being renamed or the key being refused, not a quiet "
            f"week.")
    return out


def as_classified(item: dict) -> dict:
    """The `classified` half of build_signal, derived rather than generated.

    Every value is read off the response or is a fixed editorial line, so
    nothing on the record can be something a model believed. The report title
    is quoted, never paraphrased, which is also why every figure in the summary
    is present in `raw_text` by construction.
    """
    company = item["company"]
    return {
        "company": company,
        "pillar": "leadership_change",
        # The source does not separate a joiner from a leaver. See the DIRECTION
        # note in the module docstring: `neutral` is the honest answer and
        # `displacement` would put this inside the sibling tracker's scope.
        "signal_direction": "neutral",
        "headline": item["headline"],
        "summary": (
            f"{company} disclosed a leadership change to Korea's Financial "
            f"Supervisory Service through its DART system, filed under the "
            f"report title \"{item['report_nm']}\", which the Supervisory "
            f"Service publishes in English as \"{item['report_label']}\". "
            f"The receipt number of the filing is {item['rcept_no']}. The "
            f"title records that the change occurred and does not state "
            f"whether the officer joined or left."
        ),
        "talent_readthrough": (
            "A Korean listed company must tell the exchange when its "
            "representative director changes, and must separately report the "
            "appointment, dismissal or early retirement of an independent "
            "director. That makes this a complete feed for those two roles "
            "rather than a selective one: it covers the small and mid-cap "
            "employers no outlet writes about on the same basis as the "
            "chaebol. Two limits are worth reading with it. The mandated item "
            "covers the CEO and independent directors, so ordinary inside "
            "directors are elected at a shareholder meeting and do not appear "
            "here. And the report title names the change without naming its "
            "direction, so a departure and an arrival look identical from the "
            "outside; the filing itself distinguishes them and this record "
            "does not guess."
        ),
        "country": "South Korea",
        "employer_type": item.get("employer_type") or "",
        # A statutory disclosure made to the regulator that collects it.
        # infer_confidence caps this at what the host is worth, so it lands at
        # 'verified' only while dart.fss.or.kr is a listed primary source domain.
        "confidence": "verified",
    }
