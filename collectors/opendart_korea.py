"""OpenDART — Korea's leadership spine, which is the report NAME and not a code.

South Korea's Financial Supervisory Service runs DART, the mandatory disclosure
registry, and exposes it through the keyed OpenDART API. This collector reads
ONE endpoint, the date-ranged disclosure list:

    https://opendart.fss.or.kr/api/list.json
        ?crtfc_key=...&bgn_de=YYYYMMDD&end_de=YYYYMMDD
        &pblntf_detail_ty=E005|I001&page_no=N&page_count=100

WHAT WAS LOOKED FOR AND WHAT IS ACTUALLY THERE. The India unlock was SEBI's
mandated Regulation 30 CATEGORY: a machine-readable label on every officer
change, the same shape as Item 5.02 of a US Form 8-K. Korea's published API
list was walked end to end on 2026-07-29 (six groups, 84 endpoints, from
`https://opendart.fss.or.kr/guide/main.do?apiGrpCd=DS001..DS006`) looking for
the equivalent. It does not exist at code level:

  * **`pblntf_detail_ty` stops one level too coarse.** The whole typed taxonomy
    is 10 types and ~60 detail codes. Every Korea Exchange timely disclosure —
    supply contracts, dividends, buybacks, CEO changes, litigation — arrives
    under the single code `I001` (수시공시). There is no `I001-3-a`. That is
    the Form 6-K problem: a filing type with no item taxonomy inside it.
  * **The 주요사항보고서 (major report) family carries no officer item at all.**
    All 36 endpoints in group DS005 were read: insolvency, capital raises,
    buybacks, mergers, divisions, asset transfers, business suspension. Not one
    is an appointment or a departure. The brief that asked for this connector
    named that family as a candidate; it is a dead end, measured rather than
    assumed.
  * **The periodic-report endpoints ARE snapshots, exactly as feared.**
    `exctvSttus.json` (임원현황) returns every sitting officer as of
    `stlm_dt` — name, position, tenure as free text ("3년 6개월"), term expiry.
    `empSttus.json` (직원현황) returns headcount by division and gender.
    Neither states that anybody was appointed, and neither carries an
    appointment DATE. Turning them into events would mean diffing year N
    against year N-1 and stamping the difference with a date the source never
    stated, which "no source URL, no record" and "the model never invents a
    number" both forbid. They are refused. See REFUSED_ENDPOINTS.

WHAT DOES WORK: the exchange's own report NAME is a fixed vocabulary. Measured
unauthenticated against DART's public search (`dart.fss.or.kr/dsab007/`, which
robots.txt permits) over 2026-05-01 to 2026-07-29, 8,363 disclosures:

    독립이사의선임ㆍ해임또는중도퇴임에관한신고   150   (detail type E005)
    대표이사변경                                  79   (inside I001)
    대표이사(대표집행임원)변경(안내공시)          28   (inside I001)
    대표집행임원변경                               4   (inside I001)
                                              ------
                                                 261  in 90 days, ~1,060/year

8,211 `I001` filings in that window collapse into 360 DISTINCT names, and the
four above recur identically. These are KRX's own form titles, generated by the
exchange's filing system, not sentences a company composed — the same kind of
value as BSE's `SUBCATNAME`. `E005` is better still: one detail code whose every
row (150 of 150) carries one name, and that name says what happened —
appointment, dismissal or early retirement of an independent director.

So Korea is real but NARROW. India files ~13,000 leadership disclosures a year
because Regulation 30 covers every director and every key managerial person.
Korea's mandatory timely-disclosure item covers the REPRESENTATIVE DIRECTOR
(the CEO) and, separately, independent directors. Ordinary inside directors are
elected at a shareholder meeting and appear only in the meeting's result, which
is untyped prose. That gap is the honest price and it is not closable from here.

THE DIRECTION IS NOT IN THE SOURCE, so no row claims one. `대표이사변경` says
"change of representative director" and `독립이사의선임ㆍ해임또는중도퇴임에관한신고`
names all three possibilities in one title. Neither separates a joiner from a
leaver, so every row here is `neutral`, as India's departures already are.
`displacement` is never used: one officer leaving is a change of leadership, not
a workforce reduction, and workforce reductions are the sibling tracker's scope.

FOUR TRAPS, each found by reading the API or fetching a real filing.

1. **A missing key is an HTTP 302 to an HTML page, and a BAD key is an HTTP 200.**
   Verified live on 2026-07-29 without any credential: `list.json` with no
   `crtfc_key` returns 302 and an HTML error document, while a syntactically
   valid but unregistered key returns `200 {"status":"010"}`. So neither
   "status_code == 200" nor "the body parsed as JSON" means success — the
   `status` field is the only authority. This matters here more than usual:
   CLAUDE.md records that mapping a MISSING GitHub secret sets the environment
   variable to empty string, which is exactly how a leadership dispatch once
   went green having stored nothing. An empty key is refused before any request.

2. **The English DART viewer 200s with the single word "Reject" for one filing
   in five.** `englishdart.fss.or.kr/dsbh001/main.do?rcpNo=` looked like the
   ideal `source_url` — it is the same document with FSS's own English labels,
   and no robots.txt governs that host. Measured on 20 real filings from the
   allowlist: 16 rendered, **4 returned a page whose entire body is "Reject"**,
   among them Kia and Korea Gas Corporation. A citation that answers 200 with
   one word is worse than a 404, because a link checker calls it live. So
   `source_url` is the canonical Korean viewer, `dart.fss.or.kr/dsaf001/main.do
   ?rcpNo={rcept_no}`, which is the form OpenDART's own field documentation
   gives for every `rcept_no` and which is stable for the life of the filing.
   Note honestly: **dart.fss.or.kr/robots.txt disallows `/dsaf001/main.do`.**
   Nothing here fetches it — the collector talks only to
   `opendart.fss.or.kr/api/`, which serves no robots.txt — but `link_check.py`
   will record these URLs as `robots` rather than checking them, and that is the
   correct outcome rather than a defect to route around.

3. **A parent files its subsidiary's CEO change under its own name.**
   `대표이사변경 (자회사의 주요경영사항)` is a chaebol-shaped disclosure: the
   listed parent reports a change at a subsidiary, and `corp_name` is the
   PARENT. Miwon Holdings and MAEIL HOLDINGS both filed one in the window.
   Storing it would attribute a subsidiary's change to its parent, and the
   subsidiary is named only inside the document. Refused, by name, in
   REFUSED_REPORT_NAMES — 2 of 261 in 90 days.

4. **Full-width digits break the verbatim-figure guard.** `validate._numbers_in`
   tokenises with `\d`, which matches U+FF10..FF19, and `_normalize_number`
   does not fold them — so `１２３` in a summary and `123` in `raw_text` compare
   unequal and a correct record is discarded silently. Korean filings can carry
   them. `_squeeze` folds full-width digits to ASCII on the way in, and every
   figure in the summary is a substring of the SAME string quoted into
   `raw_text`, so the round trip holds twice over. NFKC would have been the
   obvious fix and is WRONG here: it rewrites U+318D (the ㆍ in
   독립이사의선임ㆍ해임...) to U+119E, silently mangling the report name the
   allowlist matches on.

NAMES. The employer stored is `corp_name_eng` from `company.json`, the
company's OWN registered English name, fetched once per company per run and
cached in memory. It is not a nicety: `company_key` passes Hangul through
unchanged, and the WordPress slug is `[^a-z0-9]+ -> -`, so a Korean key yields
an empty slug and falls back to a percent-encoded one — and HANDOVER.md records
that percent-encoded slugs 404 on this host. A filer whose `corp_name_eng` is
blank is DECLINED rather than romanised: this file invents no transliteration.
The Korean `corp_name` is still quoted into `raw_text`, because that is the
filer's own name and the record should carry it.

WHAT IS NOT STORED, on purpose. `stock_code` is a 6-digit KRX code and is not
written to `ticker`: that column is SEC-authoritative everywhere else in this
tracker (`pipeline/identity.py` resolves it from `company_tickers.json`), and
putting two vocabularies in one column is how a filter starts lying. `adres`
from `company.json` would give a registered address, but a legal seat is not
where an appointment happened and `identity.py` is already the single authority
for `hq_city`. No city is guessed; Korean rows place at country level, as
Indian ones do.

UNPROVEN UNTIL THE FIRST REAL RUN, stated plainly because no authenticated call
has ever been made from here: the exact `list.json` row shape (taken from FSS's
published response spec, not from a response), whether `corp_name_eng` is
populated for every listed filer, and the real request cost of one window. The
documented quota is 20,000 requests a day; a 7-day window is ~8 list pages plus
one `company.json` per distinct employer, so roughly 30 requests a week.
"""

